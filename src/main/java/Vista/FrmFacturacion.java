    private void cmbOrdenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbOrdenActionPerformed
        if (cmbOrden.getSelectedItem() == null) {
            return;
        }

        String numero = cmbOrden.getSelectedItem().toString();

        OrdenTrabajo orden = controladorOrdenes.buscarOrden(numero);

        if (orden == null) {
            return;
    }   

        double subtotalServicios = 0;
        double subtotalRepuestos = 0;

    for (modelo.Servicios servicio : orden.getServicios()) {
        subtotalServicios += servicio.getPrecioBase();
    }

    for (modelo.Inventario repuesto : orden.getRepuestos()) {
        subtotalRepuestos += repuesto.getPrecioUnitario();
    }   

    double subtotal = subtotalServicios + subtotalRepuestos;
    double impuesto = subtotal * 0.15;
    double total = subtotal + impuesto;

    txtSubtotalServicios.setText(String.valueOf(subtotalServicios));
    txtSubtotalRepuestos.setText(String.valueOf(subtotalRepuestos));
    txtImpuesto.setText(String.valueOf(impuesto));
    txtTotal.setText(String.valueOf(total));
    }//GEN-LAST:event_cmbOrdenActionPerformed

    private void BtnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCalcularActionPerformed
        try {
    double total = Double.parseDouble(txtTotal.getText());
    double pago = Double.parseDouble(txtPago.getText());

    double cambio = controlador.calcularCambio(total, pago);

    txtCambio.setText(String.format("%.2f", cambio));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Ingresa un pago válido.");

        } catch (PagoInsuficienteException e) {
            JOptionPane.showMessageDialog(this,
                e.getMessage());
        }
    }//GEN-LAST:event_BtnCalcularActionPerformed

    private void BtnFacturarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnFacturarActionPerformed
       try {
    if (cmbOrden.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Selecciona una orden de trabajo.");
        return;
    }

    double subtotalServicios =
            Double.parseDouble(txtSubtotalServicios.getText());

    double subtotalRepuestos =
            Double.parseDouble(txtSubtotalRepuestos.getText());

    double impuesto =
            Double.parseDouble(txtImpuesto.getText());

    double total =
            Double.parseDouble(txtTotal.getText());

    double pago =
            Double.parseDouble(txtPago.getText());

    double cambio = controlador.calcularCambio(total, pago);

    String numero = cmbOrden.getSelectedItem().toString();
    OrdenTrabajo orden = controladorOrdenes.buscarOrden(numero);

    Facturacion factura = new Facturacion(
            siguienteNumeroFactura,
            orden,
            subtotalServicios,
            subtotalRepuestos,
            impuesto,
            total,
            pago,
            cambio
    );
    
    try {
        for (Inventario repuesto : orden.getRepuestos()) {

        controladorRepuestos.descontarRepuesto(
                String.valueOf(repuesto.getCodigo()), 1
        );
    }

        } catch (StockInsuficienteException e) {

    JOptionPane.showMessageDialog(this, e.getMessage());
    return;
}

    controlador.crearFactura(factura);

    siguienteNumeroFactura++;
    txtNumeroFactura.setText(String.valueOf(siguienteNumeroFactura));

    StringBuilder recibo = new StringBuilder();

recibo.append("       AUTOTECH SOLUTIONS\n");
recibo.append("     FACTURA DE SERVICIOS\n");
recibo.append("--------------------------------\n");
recibo.append("Factura N.º: ").append(factura.getNumeroFactura()).append("\n");
recibo.append("Orden N.º: ").append(orden.getNumero()).append("\n");
recibo.append("Cliente: ").append(orden.getCliente().getNombre())
        .append(" ").append(orden.getCliente().getApellido()).append("\n");
recibo.append("Fecha: ").append(
        new java.text.SimpleDateFormat("dd/MM/yyyy")
                .format(orden.getFecha())).append("\n");
recibo.append("--------------------------------\n");

recibo.append("SERVICIOS:\n");
for (modelo.Servicios servicio : orden.getServicios()) {
    recibo.append(servicio.getDescripcion())
            .append(" - L ").append(servicio.getPrecioBase()).append("\n");
}

recibo.append("\nREPUESTOS:\n");
for (modelo.Inventario repuesto : orden.getRepuestos()) {
    recibo.append(repuesto.getNombre())
            .append(" - L ").append(repuesto.getPrecioUnitario()).append("\n");
}

        recibo.append("--------------------------------\n");
        recibo.append("Subtotal servicios: L ").append(subtotalServicios).append("\n");
        recibo.append("Subtotal repuestos: L ").append(subtotalRepuestos).append("\n");
        recibo.append("ISV (15%): L ").append(impuesto).append("\n");
        recibo.append("TOTAL: L ").append(total).append("\n");
        recibo.append("Pago recibido: L ").append(pago).append("\n");
        recibo.append("Cambio: L ").append(cambio).append("\n");
        recibo.append("--------------------------------\n");
        recibo.append(" ¡Gracias por su preferencia!");

        JOptionPane.showMessageDialog(this,
        recibo.toString(),
        "Factura generada",
        JOptionPane.INFORMATION_MESSAGE);

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Verifica que hayas ingresado un pago válido.");

} catch (PagoInsuficienteException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_BtnFacturarActionPerformed

