    private void TablaServiciosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TablaServiciosMouseClicked
        int fila = TablaServicios.getSelectedRow();

if (fila >= 0) {

    txtCodigo.setText(
        TablaServicios.getValueAt(fila, 0).toString());

    txtDescripcion.setText(
        TablaServicios.getValueAt(fila, 1).toString());

    txtPrecioBase.setText(
        TablaServicios.getValueAt(fila, 2).toString());

    txtTiempo.setText(
        TablaServicios.getValueAt(fila, 3).toString());

    txtCodigo.setEditable(false);
    txtDescripcion.setEditable(false);
        }
    }//GEN-LAST:event_TablaServiciosMouseClicked

    private void BtnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnModificarActionPerformed
       int fila = TablaServicios.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this,
            "Seleccione un servicio de la tabla");
    return;
}

try {

    String codigo = txtCodigo.getText().trim();
    String descripcion = txtDescripcion.getText().trim();

    double precio = Double.parseDouble(txtPrecioBase.getText().trim());
    int tiempo = Integer.parseInt(txtTiempo.getText().trim());

    if (precio <= 0) {
        JOptionPane.showMessageDialog(this,
                "El precio debe ser mayor que cero");
        return;
    }

    if (tiempo <= 0) {
        JOptionPane.showMessageDialog(this,
                "El tiempo debe ser mayor que cero");
        return;
    }

    Servicios servicio = new Servicios(
            Integer.parseInt(codigo),
            descripcion,
            precio,
            tiempo
    );

    controlador.actualizarServicio(codigo, servicio);

    TablaServicios.setValueAt(precio, fila, 2);
    TablaServicios.setValueAt(tiempo, fila, 3);

    JOptionPane.showMessageDialog(this,
            "Servicio modificado correctamente");

    txtCodigo.setText("");
    txtDescripcion.setText("");
    txtPrecioBase.setText("");
    txtTiempo.setText("");

    txtCodigo.setEditable(true);
    txtDescripcion.setEditable(true);

    TablaServicios.clearSelection();

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Ingrese valores numéricos válidos en precio y tiempo");

}
    }//GEN-LAST:event_BtnModificarActionPerformed


