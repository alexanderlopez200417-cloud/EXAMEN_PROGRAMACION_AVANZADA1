    private void cargarGrafico() {

    List<ProductoGrafico> datos = new ArrayList<>();

    for (Inventario repuesto : controlador.listarRepuestos()) {

        datos.add(new ProductoGrafico(
                repuesto.getNombre(),
                repuesto.getCantidad()
        ));
    }

        grafico.setDatos(datos);
    }
    
    public void actualizarGrafico() {
        cargarGrafico();
    }

