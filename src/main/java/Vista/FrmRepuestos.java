    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
       try {
    int codigo = Integer.parseInt(txtCodigo.getText().trim());
    String nombre = txtNombre.getText().trim();
    int cantidad = Integer.parseInt(txtCantidad.getText().trim());
    int precio = Integer.parseInt(txtPrecio.getText().trim());
    int stock = Integer.parseInt(txtStock.getText().trim());

    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el nombre del repuesto");
        return;
    }

    if (cantidad < 0 || precio <= 0 || stock < 0) {
        JOptionPane.showMessageDialog(this, "No se permiten cantidades negativas y el precio debe ser positivo");
        return;
    }

    if (controlador.buscarRepuesto(String.valueOf(codigo)) != null) {
        JOptionPane.showMessageDialog(this, "Ese código ya existe");
        return;
    }

    Inventario repuesto = new Inventario(
        codigo, nombre, cantidad, precio, stock, null
    );

    controlador.crearRepuesto(repuesto);

    cargarRepuestos();

    JOptionPane.showMessageDialog(this, "Repuesto registrado correctamente");

    txtCodigo.setText("");
    txtNombre.setText("");
    txtCantidad.setText("");
    txtPrecio.setText("");
    txtStock.setText("");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos");
}
    }//GEN-LAST:event_BtnGuardarActionPerformed

