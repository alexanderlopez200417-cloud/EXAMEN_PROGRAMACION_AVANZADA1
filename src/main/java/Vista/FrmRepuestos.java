    private void cargarRepuestos() {

    modeloTabla.setRowCount(0);

    for (Inventario repuesto : controlador.listarRepuestos()) {

        String estado = repuesto.getCantidad() <= repuesto.getStock()
                ? "Stock bajo" : "Disponible";

        modeloTabla.addRow(new Object[]{
            repuesto.getCodigo(),
            repuesto.getNombre(),
            repuesto.getCantidad(),
            repuesto.getPrecioUnitario(),
            repuesto.getStock(),
            estado
        });
    }
}
    private void verificarAlertas() {

    for (Inventario repuesto : controlador.listarRepuestos()) {

        if (repuesto.getCantidad() <= repuesto.getStock()) {

            JOptionPane.showMessageDialog(
                this,
                "¡Stock bajo!\nEl repuesto " + repuesto.getNombre()
                + " tiene solamente " + repuesto.getCantidad()
                + " unidades disponibles."
            );
        }
    }
}

