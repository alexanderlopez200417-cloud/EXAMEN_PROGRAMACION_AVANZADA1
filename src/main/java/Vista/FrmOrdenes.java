    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
        String fecha = txtFecha.getText().trim();
        String diagnostico = txtDiagnostico.getText().trim();
        String estado = txtEstado.getText().trim();

    if (fecha.isEmpty() || diagnostico.isEmpty() || estado.isEmpty()
        || cmbCliente.getSelectedItem() == null
        || cmbVehiculo.getSelectedItem() == null
        || cmbServicio.getSelectedItem() == null
        || cmbRepuesto.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(this,
            "Debes completar todos los campos.");
        return;
        }
    
        Clientes cliente = null;
        for (Clientes c : controladorClientes.listarClientes()) {
    String nombreCompleto = c.getNombre() + " " + c.getApellido();

    if (nombreCompleto.equals(cmbCliente.getSelectedItem())) {
        cliente = c;
        break;
    }
}

        Vehiculos vehiculo = null;
        for (Vehiculos v : controladorVehiculos.listarVehiculos()) {
            if (v.getPlaca().equals(cmbVehiculo.getSelectedItem())) {
        vehiculo = v;
        break;
    }
}

Servicios servicio = null;
for (Servicios s : controladorServicios.listarServicios()) {
    if (s.getDescripcion().equals(cmbServicio.getSelectedItem())) {
        servicio = s;
        break;
    }
}

        Inventario repuesto = null;
        for (Inventario r : controladorRepuestos.listarRepuestos()) {
            if (r.getNombre().equals(cmbRepuesto.getSelectedItem())) {
            repuesto = r;
                break;
            }
        }
        
        if (cliente == null || vehiculo == null
        || servicio == null || repuesto == null) {

         JOptionPane.showMessageDialog(this,
            "No se pudieron encontrar todos los datos seleccionados.");
            return;
        }
        
        ArrayList<Servicios> listaServicios = new ArrayList<>();
        listaServicios.add(servicio);

        ArrayList<Inventario> listaRepuestos = new ArrayList<>();
        listaRepuestos.add(repuesto);
        
        Date fechaOrden;

        try {
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        formato.setLenient(false);
        fechaOrden = formato.parse(txtFecha.getText().trim());

            } catch (java.text.ParseException e) {
            JOptionPane.showMessageDialog(this,
            "La fecha debe tener el formato dd/MM/yyyy.");
        return;
        }
        
        double costoTotal = servicio.getPrecioBase()
        + (repuesto.getPrecioUnitario() * 1);
        
        OrdenTrabajo orden = new OrdenTrabajo(
        siguienteNumeroOrden,
        fechaOrden,
        cliente,
        vehiculo,
        diagnostico,
        "",
        listaServicios,
        listaRepuestos,
        costoTotal,
        estado
    );

        BtnGuardar.setEnabled(false);
        BtnGuardar.setText("Procesando...");
        

        SwingWorker<Void, Void> trabajador = new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {

        // Simular el procesamiento durante 5 segundos
        Thread.sleep(5000);

        return null;
    }

    @Override
    protected void done() {

        controladorOrdenes.crearOrden(orden);

        siguienteNumeroOrden++;
        txtNumero.setText(String.valueOf(siguienteNumeroOrden));

        cargarOrdenes();

        txtFecha.setText("");
        txtDiagnostico.setText("");
        txtEstado.setText("");

        cmbCliente.setSelectedIndex(-1);
        cmbVehiculo.setSelectedIndex(-1);
        cmbServicio.setSelectedIndex(-1);
        cmbRepuesto.setSelectedIndex(-1);

        BtnGuardar.setEnabled(true);
        BtnGuardar.setText("Guardar");

        JOptionPane.showMessageDialog(
            FrmOrdenes.this,
            "Orden registrada correctamente."
        );
    }
};

trabajador.execute();
        
        siguienteNumeroOrden++;
        txtNumero.setText(String.valueOf(siguienteNumeroOrden));

        JOptionPane.showMessageDialog(this,
        "PROCESANDO...");
        
        cargarOrdenes();
        
        txtFecha.setText("");
        txtDiagnostico.setText("");
        txtEstado.setText("");

        cmbCliente.setSelectedIndex(-1);
        cmbVehiculo.setSelectedIndex(-1);
        cmbServicio.setSelectedIndex(-1);
        cmbRepuesto.setSelectedIndex(-1);
    }//GEN-LAST:event_BtnGuardarActionPerformed

    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
       int fila = TablaOrdenes.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
            "Selecciona una orden de la tabla para eliminar.");
        return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(this,
        "¿Estás seguro de eliminar esta orden?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION);

        if (confirmacion == JOptionPane.YES_OPTION) {
         String numero = TablaOrdenes.getValueAt(fila, 0).toString();

         controladorOrdenes.eliminarOrden(numero);

        cargarOrdenes();

        JOptionPane.showMessageDialog(this,
            "Orden eliminada correctamente.");
        }
    }//GEN-LAST:event_BtnEliminarActionPerformed


