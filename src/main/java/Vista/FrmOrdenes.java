    private void cargarClientes() {

    cmbCliente.removeAllItems();

    for (Clientes cliente : controladorClientes.listarClientes()) {

        String nombreCompleto =
                cliente.getNombre() + " " + cliente.getApellido();

        cmbCliente.addItem(nombreCompleto);
        }
    }
    
    public void actualizarClientes() {
        cargarClientes();
    }
    
    private void cargarVehiculos() {

    cmbVehiculo.removeAllItems();

    for (Vehiculos vehiculo : controladorVehiculos.listarVehiculos()) {
        cmbVehiculo.addItem(vehiculo.getPlaca());
        }
    }
    
    private void cargarOrdenes() {
    modeloTabla.setRowCount(0);

    for (OrdenTrabajo orden : controladorOrdenes.listarOrdenes()) {
        modeloTabla.addRow(new Object[]{
            orden.getNumero(),
            orden.getFecha(),
            orden.getCliente().getNombre() + " " + orden.getCliente().getApellido(),
            orden.getVehiculo().getPlaca(),
            orden.getServicios().get(0).getDescripcion(),
            orden.getEstado(),
            orden.getDiagnostico()
            });
        }
    }
    
    public void actualizarVehiculos() {
        cargarVehiculos();
    }
    private void cargarServicios() {
    cmbServicio.removeAllItems();

    for (Servicios servicio : controladorServicios.listarServicios()) {
        cmbServicio.addItem(servicio.getDescripcion());
    }
}
    public void actualizarServicios() {
        cargarServicios();
        }
    
    public void actualizarRepuestos() {
        cargarRepuestos();
    }
    
    private void cargarRepuestos() {
    cmbRepuesto.removeAllItems();

    for (Inventario repuesto : controladorRepuestos.listarRepuestos()) {
        cmbRepuesto.addItem(repuesto.getNombre());
    }
    
    
}

